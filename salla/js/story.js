// ترتيب ثابت (لكنه مخلوط) لخيارات كل سؤال، حتى يطابق التسجيل الصوتي ترتيب البوابات
export function optionOrder(qText, n) {
  let h = 2166136261;
  for (const ch of qText) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619) >>> 0; }
  const idx = [...Array(n).keys()];
  for (let i = n - 1; i > 0; i--) { h = Math.imul(h ^ (h >>> 13), 1274126177) >>> 0; const j = h % (i + 1); [idx[i], idx[j]] = [idx[j], idx[i]]; }
  // لا نسمح أن تكون الإجابة الصحيحة (رقم 0) في المكان نفسه دائمًا: الخلط يكفي
  return idx;
}
export const stripEmoji = (s) => s.replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/gu, '').replace(/\s+/g, ' ').trim();
// نص التسجيل الصوتي للسؤال: السؤال ثم الخيارات بألوان البوابات
export function questionSpeech(q) {
  const ord = optionOrder(q.q, q.o.length);
  return stripEmoji(q.q) + ' ' + ord.map((k, i) => `البوابةُ ${GATE_COLORS[i].ar}: ${stripEmoji(q.o[k])}.`).join(' ');
}
// معرّف التسجيل الصوتي لسطر
export function lineId(scope, key, line, sex) { return `${scope}_${key}${(line.b !== line.g || line.b.includes('{N}')) ? '_' + sex : ''}`; }

// يُعيد نص السطر حسب الجنس واسم البطل
export function lineText(line, sex, name) {
  return (sex === 'g' ? line.g : line.b).replaceAll('{N}', name);
}

